"""Problem definition structures and defaults.

Python port of AMIGO_private_defaults / AMIGO_public_defaults / the
AMIGO_check_* family, trimmed to the costMex + charmodelC path
(see basic_amigo/core/).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np
import re

from mini_amigo.errors import InputError

DEFAULT_N_THREADS = 1


def _arr(x, dtype=float, shape: Optional[tuple] = None) -> np.ndarray:
    a = np.asarray(x, dtype=dtype)
    if shape is not None:
        a = a.reshape(shape)
    return a


@dataclass
class Experiment:
    """Per-experiment scheme (inputs.exps.* cell arrays)."""

    n_obs: int = 0
    obs: list[str] = field(default_factory=list)          # e.g. "Xobs=X"
    obs_names: list[str] = field(default_factory=list)
    t_s: np.ndarray = field(default_factory=lambda: np.zeros(0))
    t_in: float = 0.0
    t_f: float = 0.0
    exp_y0: np.ndarray = field(default_factory=lambda: np.zeros(0))
    u_interp: str = "linear"
    t_con: np.ndarray = field(default_factory=lambda: np.zeros(0))
    u: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (n_stim, n_steps)
    n_steps: int = 0
    n_linear: int = 0
    n_pulses: int = 0
    u_min: Optional[np.ndarray] = None
    u_max: Optional[np.ndarray] = None
    exp_data: Optional[np.ndarray] = None    # (n_s, n_obs)
    error_data: Optional[np.ndarray] = None  # (n_s, n_obs)
    w_obs: Optional[np.ndarray] = None       # (n_obs,)
    # derived by check_exps / uinterp:
    pend: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (n_stim, ncon)
    n_con: int = 0
    index_observables: Optional[np.ndarray] = None  # 0-based; None -> OBS func
    Q: Optional[np.ndarray] = None                  # (n_s, n_obs)

    @property
    def n_s(self) -> int:
        return int(self.t_s.size)


@dataclass
class Model:
    n_st: int = 0
    st_names: list[str] = field(default_factory=list)
    eqns: list[str] = field(default_factory=list)
    n_par: int = 0
    par_names: list[str] = field(default_factory=list)
    par: np.ndarray = field(default_factory=lambda: np.zeros(0))
    n_stimulus: int = 0
    stimulus_names: list[str] = field(default_factory=list)
    exe_type: str = "costMex"
    input_model_type: str = "charmodelC"
    overwrite_model: bool = True
    positive_states: int = 0
    # generated by prep:
    odes_file: str = ""
    lib_file: str = ""


@dataclass
class PEsol:
    id_global_theta: object = "all"          # 'all' | 'none' | list[str]
    global_theta_min: Optional[np.ndarray] = None
    global_theta_max: Optional[np.ndarray] = None
    global_theta_guess: Optional[np.ndarray] = None
    # derived:
    n_global_theta: int = 0
    index_global_theta: np.ndarray = field(default_factory=lambda: np.zeros(0, dtype=int))


@dataclass
class IvpSol:
    rtol: float = 1e-5      # AMIGO_public_defaults.m
    atol: float = 1e-7
    max_step_size: float = np.inf
    ivp_maxnumsteps: int = 1_000_000
    max_error_test_fails: int = 50   # AMIGO_model.c default
    nthreads: int = 1


@dataclass
class Inputs:
    """Equivalent of the MATLAB `inputs` struct for the costMex path."""

    model: Model = field(default_factory=Model)
    exps: list[Experiment] = field(default_factory=list)
    PEsol: PEsol = field(default_factory=PEsol)
    ivpsol: IvpSol = field(default_factory=IvpSol)
    results_folder: str = "Problem"
    short_name: str = "problem"
    data_type: str = "real"          # AMIGO_private_defaults: 'pseudo'
    noise_type: str = "homo_var"
    PEcost_type: str = "lsq"
    lsq_type: str = "Q_I"

    @property
    def n_exp(self) -> int:
        return len(self.exps)


def check_inputs(inputs: Inputs) -> None:
    """Trimmed AMIGO_check_model/check_exps/check_theta (costMex path).

    Validates the user definition and fills derived fields in-place
    (theta indices, pend, n_con, Q, w_obs, index_observables).
    """
    m = inputs.model
    if m.exe_type != "costMex":
        raise InputError("only inputs.model.exe_type = 'costMex' is supported")
    if m.input_model_type != "charmodelC":
        raise InputError("costMex requires inputs.model.input_model_type = 'charmodelC'")
    if m.n_st < 1 or m.n_par < 1:
        raise InputError("model.n_st and model.n_par must be >= 1 (error_model_002)")
    n_ode = sum(1 for eq in m.eqns if re.match(r"^d\w+=", eq))
    if n_ode != m.n_st:
        raise InputError(f"ODE equations ({n_ode}) != model.n_st={m.n_st}")
    if len(m.par_names) != m.n_par:
        raise InputError("len(model.par_names) != model.n_par")
    if len(m.st_names) != m.n_st:
        raise InputError("len(model.st_names) != model.n_st")
    if m.par.size != m.n_par:
        raise InputError("model.par must have model.n_par entries")
    if m.n_stimulus > 0 and len(m.stimulus_names) != m.n_stimulus:
        raise InputError("len(model.stimulus_names) != model.n_stimulus")
    if not inputs.exps:
        raise InputError("at least one experiment is required")

    _check_theta(inputs)

    for iexp, e in enumerate(inputs.exps, start=1):
        if e.exp_y0.size != m.n_st:
            raise InputError(f"exp {iexp}: exp_y0 must have n_st entries")
        if e.t_f <= e.t_in:
            raise InputError(f"exp {iexp}: t_f must be > t_in (error_exps_003)")
        if e.t_s.size < 2:
            raise InputError(f"exp {iexp}: at least 2 sampling times required")
        if e.n_obs > 0 and (len(e.obs) != e.n_obs or len(e.obs_names) != e.n_obs):
            raise InputError(f"exp {iexp}: obs/obs_names must have n_obs entries")

        _check_stimulus(inputs, e, iexp)

        # observables: empty index_observables -> generated OBS function
        # (mini_AMIGO_prep.m:94-99)
        if e.n_obs > 0:
            e.index_observables = None
        else:
            e.index_observables = np.zeros(0, dtype=np.int32)

        if e.w_obs is None:
            e.w_obs = np.ones(e.n_obs)
        # lsq_type Q_I (AMIGO_check_Q.m:48-53)
        e.Q = np.ones((e.n_s, e.n_obs)) if e.n_obs else np.zeros((e.n_s, 0))

    pe = inputs.PEsol
    if pe.n_global_theta > 0:
        if pe.global_theta_guess is None:
            if pe.global_theta_min is not None and pe.global_theta_max is not None:
                pe.global_theta_guess = 0.5 * (pe.global_theta_min + pe.global_theta_max)
            else:
                pe.global_theta_guess = m.par[pe.index_global_theta].copy()
        if pe.global_theta_min is None:
            pe.global_theta_min = np.zeros(pe.n_global_theta)
        if pe.global_theta_max is None:
            pe.global_theta_max = np.full(pe.n_global_theta, 1e30)
        if np.any(pe.global_theta_max < pe.global_theta_min):
            raise InputError("global_theta_max < global_theta_min (error_bounds_013)")
    else:
        pe.global_theta_guess = np.zeros(0)
        pe.global_theta_min = np.zeros(0)
        pe.global_theta_max = np.zeros(0)


def _check_theta(inputs: Inputs) -> None:
    """AMIGO_set_theta_index (global parameters only)."""
    m, pe = inputs.model, inputs.PEsol
    idg = pe.id_global_theta
    if isinstance(idg, str):
        if idg == "all":
            pe.index_global_theta = np.arange(m.n_par, dtype=int)
            pe.n_global_theta = m.n_par
        elif idg == "none":
            pe.index_global_theta = np.zeros(0, dtype=int)
            pe.n_global_theta = 0
        else:
            raise InputError(f"PEsol.id_global_theta must be 'all', 'none' or a list (got {idg!r})")
    else:
        names = list(idg)
        idx = []
        for nm in names:
            if nm not in m.par_names:
                raise InputError(f"PESol.id_global_theta: unknown parameter {nm!r}")
            idx.append(m.par_names.index(nm))
        pe.index_global_theta = np.asarray(idx, dtype=int)
        pe.n_global_theta = len(idx)

    for name, arr in (("global_theta_min", pe.global_theta_min),
                      ("global_theta_max", pe.global_theta_max),
                      ("global_theta_guess", pe.global_theta_guess)):
        if arr is not None and np.asarray(arr).size != pe.n_global_theta:
            raise InputError(f"PESol.{name} must have n_global_theta entries")

    for name in ("global_theta_min", "global_theta_max", "global_theta_guess"):
        arr = getattr(pe, name)
        if arr is not None:
            setattr(pe, name, np.asarray(arr, dtype=float).ravel())


def _check_stimulus(inputs: Inputs, e: Experiment, iexp: int) -> None:
    """AMIGO_check_exps stimulus branch + AMIGO_uinterp (step/linear/sustained/pulse)."""
    m = inputs.model
    if m.n_stimulus == 0:
        e.u_interp = "sustained"
        e.u = np.zeros((1, 1))
        e.pend = np.zeros((1, 1))
        e.t_con = np.asarray([e.t_in, e.t_f], dtype=float)
        e.n_steps = 1
        e.n_con = 1
        return

    interp = e.u_interp
    if interp in ("sustained",):
        u = np.atleast_2d(_arr(e.u))
        if u.shape[0] != m.n_stimulus:
            raise InputError(f"exp {iexp}: u must be n_stimulus x 1 for sustained")
        e.pend = np.zeros((m.n_stimulus, 1))
        e.n_steps = 1
        e.n_con = 1
        e.u = u[:, :1]
        if e.t_con.size == 0:
            e.t_con = np.asarray([e.t_in, e.t_f], dtype=float)
    elif interp in ("step", "stepf"):
        u = np.atleast_2d(_arr(e.u))
        if u.shape[0] != m.n_stimulus:
            raise InputError(f"exp {iexp}: u must be n_stimulus x n_steps")
        if e.n_steps <= 1:
            e.n_steps = 1
            e.t_con = np.asarray([e.t_in, e.t_f], dtype=float)
        if e.t_con.size < e.n_steps + 1:
            raise InputError(
                f"exp {iexp}: t_con must have n_steps+1 entries (error_exps_007)")
        e.t_con = _arr(e.t_con).ravel()[: e.n_steps + 1]
        e.pend = np.zeros((m.n_stimulus, e.n_steps))
        e.u = u[:, : e.n_steps]
        e.n_con = e.n_steps
    elif interp in ("linear", "linearf"):
        u = np.atleast_2d(_arr(e.u))
        if u.shape[0] != m.n_stimulus:
            raise InputError(f"exp {iexp}: u must be n_stimulus x n_linear")
        if e.n_linear <= 1:
            e.n_linear = 2
            e.t_con = np.asarray([e.t_in, e.t_f], dtype=float)
        if e.t_con.size < e.n_linear:
            raise InputError(f"exp {iexp}: t_con must have n_linear entries (error_exps_007)")
        e.t_con = _arr(e.t_con).ravel()[: e.n_linear]
        ncon = e.n_linear - 1
        e.pend = np.zeros((m.n_stimulus, ncon))
        for iu in range(m.n_stimulus):
            for irho in range(ncon):
                tins, tfs = e.t_con[irho], e.t_con[irho + 1]
                if tfs > tins:
                    e.pend[iu, irho] = (u[iu, irho + 1] - u[iu, irho]) / (tfs - tins)
        e.u = u[:, :ncon]
        e.n_con = ncon
    elif interp in ("pulse-up", "pulse-down"):
        if e.u_min is None or e.u_max is None:
            raise InputError(f"exp {iexp}: pulse stimuli need u_min and u_max (error_exps_008)")
        umin = np.atleast_1d(_arr(e.u_min)).ravel()
        umax = np.atleast_1d(_arr(e.u_max)).ravel()
        if e.n_pulses < 1:
            raise InputError(f"exp {iexp}: n_pulses must be >= 1")
        if interp == "pulse-up":
            e.n_steps = 2 * e.n_pulses + 1
            e.u = np.vstack([np.tile([umin[iu], umax[iu]], e.n_pulses).tolist()
                             + [umin[iu]] for iu in range(m.n_stimulus)])
        else:
            e.n_steps = 2 * e.n_pulses
            e.u = np.vstack([np.tile([umax[iu], umin[iu]], e.n_pulses).tolist()
                             for iu in range(m.n_stimulus)])
        if e.t_con.size < e.n_steps + 1:
            e.t_con = np.linspace(e.t_in, e.t_f, e.n_steps + 1)
        e.t_con = _arr(e.t_con).ravel()[: e.n_steps + 1]
        e.pend = np.zeros((m.n_stimulus, e.n_steps))
        e.n_con = e.n_steps
    else:
        raise InputError(f"exp {iexp}: no such stimuli profile: u_interp={interp!r}")

    # README gotcha 2: control times must not coincide with sampling times.
    inner = e.t_con[1:-1]
    if inner.size and np.any(np.isclose(inner[:, None], e.t_s[None, :])):
        raise InputError(
            f"exp {iexp}: t_con (inner) must not coincide with sampling times "
            "(negative stimulus index bug in simulate_amigo_model.c)")
